// Issue #194: `%`-prefixed graph and subgraph names, port bundles against the
// carried oracle (ADR-0003).
//   [ENGINES=dot,neato] [FORMATS=...] [OUT=dir] \
//     npx tsx probe.ts <base.mjs> [<head.mjs>] > out.tsv
// Inputs: every probes/*.gv. One row per probe, engine and format:
//   base, head  `eq` when stdout AND stderr equal native, `out`
//               when stdout differs, `err` when only stderr differs, `-` when
//               no head bundle was given
//   moved       `y` when head's stdout or stderr differs from base's
// stdout is compared byte for byte, except json/json0 (parsed, keys
// sorted: the port's pretty-printing and key order differ, #184) and svg (the name-bearing lines only: <title>,
// comments other than the generator's, and <g id/class> lines; the port's
// header and attribute wrapping differ).
// oos-*.gv probes are out of scope (node names, the follow-up issue): they
// are reported, never counted. Each port render runs in its own process.
import { spawnSync } from 'node:child_process';
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { oraclePreflight } from '../../../test/corpus/oracle-env.js';
import {
  ORACLE_DOT_BIN, ORACLE_GVBINDIR, ORACLE_GVBINDIR_ALL,
} from '../../../test/corpus/oracle-paths.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ENGINES = (process.env.ENGINES ?? 'dot,neato').split(',');
const FORMATS = (process.env.FORMATS ?? 'dot,xdot,json,json0,cmapx,svg,plain').split(',');
const OUT = process.env.OUT;
const TIMEOUT_MS = 60_000;

const CHILD = `
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
const [bundle, engine, fmt, file] = process.argv.slice(1);
const mod = await import(pathToFileURL(bundle).href);
const errs = [];
mod.agseterrf((s) => { errs.push(s); return 0; });
let out = '';
try { out = mod.render(mod.parse(readFileSync(file, 'utf8')), fmt, { engine }); }
catch (e) { errs.push('THROW ' + e.message); }
process.stdout.write(JSON.stringify({ out, err: errs.join('') }));
`;

interface Run { out: string; err: string }

function port(bundle: string, engine: string, fmt: string, file: string): Run {
  const r = spawnSync(process.execPath,
    ['--input-type=module', '-e', CHILD, '--', bundle, engine, fmt, file],
    { encoding: 'utf8', timeout: TIMEOUT_MS });
  if (r.error || r.status !== 0) return { out: 'FAIL', err: r.stderr ?? '' };
  return JSON.parse(r.stdout) as Run;
}

function native(engine: string, fmt: string, file: string): Run {
  const r = spawnSync(ORACLE_DOT_BIN, [`-K${engine}`, `-T${fmt}`, file], {
    env: { ...process.env, GVBINDIR: engine === 'dot' ? ORACLE_GVBINDIR : ORACLE_GVBINDIR_ALL },
    encoding: 'utf8', timeout: TIMEOUT_MS,
  });
  if (r.error || r.signal) return { out: 'FAIL', err: String(r.signal ?? r.error) };
  return { out: r.stdout, err: r.stderr };
}

/** JSON.stringify replacer that sorts object keys: json key order is #184's. */
function sortKeys(_k: string, v: unknown): unknown {
  if (v === null || typeof v !== 'object' || Array.isArray(v)) return v;
  const o = v as Record<string, unknown>;
  return Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));
}

function norm(fmt: string, s: string): string {
  if (fmt.startsWith('json')) {
    try { return JSON.stringify(JSON.parse(s), sortKeys); } catch { return s; }
  }
  if (fmt !== 'svg') return s;
  return s.split('\n').map((l) => l.trim())
    .filter((l) => /^<title>|^<!-- |^<g id=/.test(l) && !l.startsWith('<!-- Generated by'))
    .join('\n');
}

function verdict(fmt: string, n: Run, p: Run): string {
  if (norm(fmt, p.out) !== norm(fmt, n.out)) return 'out';
  return p.err === n.err ? 'eq' : 'err';
}

function save(probe: string, engine: string, fmt: string, tag: string, r: Run): void {
  if (!OUT) return;
  const d = join(OUT, probe);
  mkdirSync(d, { recursive: true });
  writeFileSync(join(d, `${engine}.${fmt}.${tag}`), r.out);
  writeFileSync(join(d, `${engine}.${fmt}.${tag}.err`), r.err);
}

function main(): void {
  const [base = '', head] = process.argv.slice(2);
  oraclePreflight(ORACLE_DOT_BIN, ORACLE_GVBINDIR, 'dot');
  oraclePreflight(ORACLE_DOT_BIN, ORACLE_GVBINDIR_ALL, 'neato');
  console.log(['probe', 'engine', 'format', 'base', 'head', 'moved'].join('\t'));
  const tally: Record<string, number> = {};
  const probes = readdirSync(join(HERE, 'probes')).filter((f) => f.endsWith('.gv')).sort();
  for (const f of probes) {
    const probe = f.replace(/\.gv$/, '');
    const file = join(HERE, 'probes', f);
    for (const engine of ENGINES) {
      for (const fmt of FORMATS) {
        const n = native(engine, fmt, file);
        const b = port(base, engine, fmt, file);
        const h = head ? port(head, engine, fmt, file) : null;
        save(probe, engine, fmt, 'native', n);
        save(probe, engine, fmt, 'base', b);
        if (h) save(probe, engine, fmt, 'head', h);
        const bv = verdict(fmt, n, b);
        const hv = h ? verdict(fmt, n, h) : '-';
        const moved = h && (h.out !== b.out || h.err !== b.err) ? 'y' : 'n';
        if (!probe.startsWith('oos-')) {
          const k = `base=${bv} head=${hv}`;
          tally[k] = (tally[k] ?? 0) + 1;
        }
        console.log([probe, engine, fmt, bv, hv, moved].join('\t'));
      }
    }
  }
  console.error(tally);
}

main();
