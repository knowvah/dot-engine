#!/usr/bin/env python3
"""Generate src/layout/neato/__fixtures__/kk-models.ts from the native harness.

Usage: gen.py <harness binary> (build it with build.sh first).
circuit and gm crash when the last-created node has an edge (circuit.c:46,
Gm[nG]); those graphs retry until a run exits 0 and the tries are recorded.
"""
import json
import pathlib
import subprocess
import sys

HARNESS = sys.argv[1]
HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
MODELS = REPO / 'src/layout/neato/__fixtures__/models'
OUT = REPO / 'src/layout/neato/__fixtures__/kk-models.ts'
MAX_TRIES = 2000
# Graphs of this directory. kk-disc-iso stands in for models/kk-disc-circuit under
# circuit: that graph exits 139 in every harness run (0 of 2000, though the
# oracle's dot survives 28 of 50), and an isolated last node removes the overflow.
LOCAL_GRAPHS = {'kk-multi', 'kk-disc-iso', 'kk-last-edge'}


def keep_negative_zero(text):
    """%.17g prints -0.0 as "-0", which Python would read as the integer 0."""
    return -0.0 if text == '-0' else int(text)


def run(args, inp=None):
    """Run until exit 0; returns (parsed JSON, tries)."""
    for tries in range(1, MAX_TRIES + 1):
        r = subprocess.run([HARNESS, *args], input=inp, capture_output=True, text=True)
        if r.returncode == 0:
            return json.loads(r.stdout, parse_int=keep_negative_zero), tries
    raise SystemExit(f'{args}: no surviving run in {MAX_TRIES}')


def gv(name):
    return (HERE if name in LOCAL_GRAPHS else MODELS) / f'{name}.gv'


subset = []
for name in ['kk-subset', 'kk-len-subset', 'kk-disc-circuit', 'kk-iso-circuit']:
    r, _ = run(['subset', str(gv(name))])
    assert r['gdDist'] == r['dij'], name  # subset_model copies Dij into GD_dist
    r.pop('gdDist')
    subset.append({'name': name, 'source': gv(name).read_text(), **r})


def raw(name, has_w, rows):
    lines = [f'{len(rows)} {has_w}']
    for row in rows:
        fields = [len(row['edges']), *row['edges'], *(row['ewgts'] if has_w else [])]
        lines.append(' '.join(str(f) for f in fields))
    r, _ = run(['raw'], '\n'.join(lines) + '\n')
    return {'name': name, **r}


raws = [
    # C restores non-NULL old weights by walking one block (restore_old_weights)
    raw('caller ewgts', 1, [
        {'edges': [0, 1, 2], 'ewgts': [0, 7.5, 0.25]},
        {'edges': [1, 0, 2], 'ewgts': [0, 7.5, 3.0]},
        {'edges': [2, 0, 1], 'ewgts': [0, 0.25, 3.0]},
        {'edges': [3], 'ewgts': [0]},
    ]),
    # duplicate neighbours drive deg_i + deg_j - 2*common below 0: size_t wraps
    raw('size_t wrap', 0, [
        {'edges': [0, 1, 2], 'ewgts': None},
        {'edges': [1, 2, 2, 2, 2], 'ewgts': None},
        {'edges': [2], 'ewgts': None},
    ]),
]

circuit = []
for name in ['kk-circuit', 'kk-len-circuit', 'kk-disc-iso', 'kk-iso-circuit',
             'kk-iso-len-circuit', 'kk-multi', 'kk-last-edge']:
    c, c_tries = run(['circuit', str(gv(name))])
    g, g_tries = run(['gm', str(gv(name))])
    assert c['before'] == c['after'], name
    assert c['rv'] == g['rv'] == 0, name
    circuit.append({
        'name': name, 'source': gv(name).read_text(), 'n': c['n'], 'rv': c['rv'],
        'before': c['before'], 'after': c['after'], 'gm': g['gm'],
        'circuitTries': c_tries, 'gmTries': g_tries,
    })
    print(name, 'rv', c['rv'], 'tries', c_tries, g_tries)


def js(v):
    return json.dumps(v, separators=(',', ':'))


def emit(case, keys):
    return '  {' + ', '.join(f'{k}: {js(case[k])}' for k in keys) + '},'


HEADER = """// SPDX-License-Identifier: EPL-2.0
/**
 * Expected results for the KK distance primitives, captured from a native
 * clang -O3 -flto=thin -arch arm64 harness that links the oracle's own
 * lib/neatogen/libneatogen.a (graphviz 16.1.0):
 * plans/post-16-1-followups-8/harness/T2/. Generated by its gen.py: do not hand-edit.
 *
 * `SUBSET_CASES` call `makeGraphData(MODE_KK, MODEL_SUBSET)`, `compute_new_weights`
 * and `compute_apsp_artificial_weights`; `RAW_CASES` start from hand-built rows.
 * `CIRCUIT_CASES` call `circuit_model`. It indexes Gm by the 1-based AGSEQ, so
 * `rv` is 0 on every graph and GD_dist stays at `before`. `gm` is the matrix
 * solveCircuit hands to matinv, from a copy of circuit.c with `matinv` redirected.
 * Graphs whose last-created node has an edge usually exit 139 (Gm[nG]);
 * `circuitTries` and `gmTries` are the runs it took to get one that survived.
 * `kk-last-edge` ends in a node joined to seq 1: Gm[1][n] lands in row 2 column 0.
 * `kk-disc-iso` is the disconnected graph with an isolated last node, because
 * `models/kk-disc-circuit.gv` exits 139 in every harness run.
 */

/** One `vtx_data` row; `ewgts: null` is C `NULL`. */
export interface KkRow {
  readonly edges: readonly number[];
  readonly ewgts: readonly number[] | null;
}

/** The native kkutils.c results for one set of rows. */
export interface KkWeightsCase {
  readonly name: string;
  readonly n: number;
  readonly rows: readonly KkRow[];
  /** Rows after `compute_new_weights`. */
  readonly weights: readonly KkRow[];
  /** `compute_apsp_artificial_weights`, row-major. */
  readonly dij: readonly number[];
  /** `graph[0].ewgts == NULL` after the call. */
  readonly ewgts0Null: 0 | 1;
  /** Rows after the call when the caller had ewgts, else `null`. */
  readonly after: readonly KkRow[] | null;
}

/** A `KkWeightsCase` whose rows come from `makeGraphData` on a DOT source. */
export interface KkSubsetCase extends KkWeightsCase {
  readonly source: string;
}

/** One native `circuit_model` call. All matrices are row-major. */
export interface KkCircuitCase {
  readonly name: string;
  readonly source: string;
  readonly n: number;
  readonly rv: 0 | 1;
  /** `GD_dist` before the call (`Initial_dist`). */
  readonly before: readonly number[];
  /** `GD_dist` after the call. */
  readonly after: readonly number[];
  /** `Gm` after solveCircuit set its diagonal. */
  readonly gm: readonly number[];
  readonly circuitTries: number;
  readonly gmTries: number;
}
"""

WEIGHT_KEYS = ['name', 'n', 'rows', 'weights', 'dij', 'ewgts0Null', 'after']
CIRCUIT_KEYS = ['name', 'source', 'n', 'rv', 'before', 'after', 'gm', 'circuitTries', 'gmTries']
out = [HEADER]
out.append('export const SUBSET_CASES: readonly KkSubsetCase[] = [')
out += [emit(c, ['source', *WEIGHT_KEYS]) for c in subset]
out += ['];', '', 'export const RAW_CASES: readonly KkWeightsCase[] = [']
out += [emit(c, WEIGHT_KEYS) for c in raws]
out += ['];', '', 'export const CIRCUIT_CASES: readonly KkCircuitCase[] = [']
out += [emit(c, CIRCUIT_KEYS) for c in circuit]
out += ['];', '']
OUT.write_text('\n'.join(out))
